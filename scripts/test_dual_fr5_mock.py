"""Smoke-test dual-FR5 RMB environment with mock ROS publishers."""

import argparse

import gymnasium as gym
import numpy as np

# Import registers custom environments.
import robo_manip_baselines.envs  # noqa: F401


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--steps", type=int, default=20)
    args = parser.parse_args()

    env = gym.make(
        "robo_manip_baselines/RealDualFR5Env-v0"
    )

    try:
        obs, info = env.reset()

        print("\n========== ENVIRONMENT READY ==========")
        print("Joint state shape:", obs["joint_pos"].shape)

        for name, image in info["rgb_images"].items():
            print(
                f"Camera {name}:",
                image.shape,
                image.dtype,
            )

        assert obs["joint_pos"].shape == (12,)
        assert set(info["rgb_images"]) == {"front", "hand"}

        for step in range(args.steps):
            # Placeholder action for testing only.
            # This action is NOT generated by ACT.
            action = obs["joint_pos"].copy()

            obs, reward, terminated, truncated, info = env.step(
                action
            )

            assert obs["joint_pos"].shape == (12,)
            assert np.all(np.isfinite(obs["joint_pos"]))

            print(f"[TEST] Step {step + 1}/{args.steps} OK")

        print("\n========== MOCK TEST PASSED ==========")

    finally:
        env.close()


if __name__ == "__main__":
    main()
